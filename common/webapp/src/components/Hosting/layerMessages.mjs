const fill = (text, params) => text.replace(/\{(\w+)\}/g, (_, k) => (params && params[k] !== undefined ? params[k] : ''));
export function layerText(locale, key, params) {
  const pair = pairs[key] ?? [key, key];
  const en = fill(pair[0], params);
  const zh = fill(pair[1], params);
  return locale === 'en-zh-HK' ? `${en} / ${zh}` : locale === 'zh-HK' ? zh : en;
}
